def resolve_expert(dataset_expert_id: str, dataset_experts: list[dict] | None = None) -> str:
    """Сопоставить expert_id из набора с персоной: по id, иначе по роли и стилю из данных.

    По схеме набора expert_id всегда один из трёх ключей EXPERTS, так что обычно срабатывает
    первая проверка. Остальное — запас на старые id (например, somnologist из ранних версий).
    """
    key = (dataset_expert_id or "").lower()
    if key in EXPERTS:
        return key
    hay = key
    for e in dataset_experts or []:
        if str(e.get("expert_id", "")).lower() == key:
            hay = f"{key} {e.get('role', '')} {e.get('speech_style', '')}".lower()
    for eid, e in EXPERTS.items():
        if any(m in hay for m in e["match"]):
            return eid
    return "clinician"  # безопасный дефолт: самый осторожный голос


def public_card(eid: str) -> dict:
    e = EXPERTS[eid]
    return {"id": eid, "name": e["name"], "role": e["role"], "tagline": e["tagline"], **e["card"]}
