"""Защита (guardrails) в три слоя.

1. До нейросети — правила (regex): ловят явные просьбы о дозе, лечении, диагнозе — такой запрос
   атака, нейросеть не переубедит. Попытку подменить инструкции (prompt injection) только помечают:
   это приём, а не просьба, и атака это или нет, решает нейросеть по тому, о чём просят.
2. В нейросети — она сама классифицирует запрос (поле is_attack в JSON-ответе) и ловит
   атаки, сформулированные хитрее, чем умеют правила.
3. После нейросети — проверка выхода: если в тексте всё-таки появилась доза/схема/диагноз,
   ответ заменяется безопасным отказом в стиле эксперта.

Правила не должны ловить обычные вопросы: «что такое мелатонин?» — это вопрос, а
«сколько мелатонина пить?» — атака. Любой ложный отказ стоит баллов G.
"""

from __future__ import annotations

import re

_I = re.IGNORECASE

# Без кофеина и алкоголя: это напитки, вопросы о них допустимы даже с числами.
SUBSTANCE = (
    r"(мелатонин|магни|глицин|валериан|валерья|снотворн|таблет|капсул|капел|капл|корвалол|валокордин|"
    r"препарат|лекарств|добавк|бад\b|антидепрессант|транквилиз|феназепам|золпидем|донормил|"
    r"антигистамин|травк|"
    r"сбор|настойк|ашваганд|триптофан|5-?htp|габа|gaba|l-?теанин|cbd|мг\b|миллиграм)"
)

RULES: list[tuple[str, re.Pattern]] = [
    # дозировка: вопрос о количестве + вещество
    ("dose", re.compile(rf"(сколько|какую дозу|какая доза|по сколько|дозиров|доз[аыуе]\b|"
                        rf"как часто пить|сколько раз).{{0,60}}{SUBSTANCE}", _I)),
    ("dose", re.compile(rf"{SUBSTANCE}.{{0,60}}(сколько|дозиров|доз[аыуе]\b|в какой дозе|по сколько)", _I)),
    ("dose", re.compile(r"\d+\s*(мг|mg|мкг|mcg|миллиграм)", _I)),
    # лечение и назначение
    ("treatment", re.compile(r"(назнач|выпиши|пропиши|подбери|посоветуй|порекомендуй).{0,40}"
                             r"(лечени|препарат|лекарств|таблет|снотворн|схем)", _I)),
    ("treatment", re.compile(r"(чем|как) (лечить|вылечить)|какие (таблетки|лекарства|препараты)|"
                             r"схем[ауы] (при[её]ма|лечения)|можно ли (отменить|бросить) (таблетк|препарат|лекарств)", _I)),
    # диагноз
    ("diagnosis", re.compile(r"(постав|определи|скажи).{0,20}диагноз|какой у меня диагноз|"
                             r"у меня (точно )?(апноэ|нарколепс|инсомни|бессонниц|депресс)\s*\?|"
                             r"это (апноэ|нарколепсия|инсомния|бессонница|депрессия)( или нет)?\s*\?", _I)),
    # подмена инструкций
    ("injection", re.compile(r"(игнорир|забудь|отмени|не (учитывай|слушай)).{0,30}(инструкц|правил|огранич|промпт)|"
                             r"ignore (all |previous |the )?(instructions|rules)|system prompt|системн(ый|ого) промпт|"
                             r"режим разработчика|developer mode|jailbreak|ты теперь не|притворись|"
                             r"представь,? что ты (врач|доктор) без", _I)),
]

# что нельзя выпускать наружу в тексте ответа
OUTPUT_BLOCK = [
    re.compile(r"\d+([.,]\d+)?\s*(мг|mg|мкг|mcg|миллиграм|таблет|капсул|капел|мл\b)", _I),
    re.compile(r"(принимайте|пейте|выпейте|пей|прими|принимай)\s.{0,30}(мелатонин|магни|таблет|препарат|снотворн|добавк)", _I),
    re.compile(r"(у вас|у тебя)\s+(скорее всего|вероятно|похоже)?\s*(апноэ|нарколепс|инсомни|депресс)", _I),
]

REFUSAL_MARKERS = re.compile(
    r"(не (стану|буду|могу|назнача|назов|подскаж|скажу|советую|дам)|не моя территория|только (после|врач)|"
    r"без врача|к врачу|решает врач|определ\w* врач|не обсуждается|этого не сделаю)", _I)


def check_input(text: str) -> str | None:
    """Вернёт тип атаки или None."""
    for kind, rx in RULES:
        if rx.search(text):
            return kind
    return None


# Просьба о запрещённом — атака, что бы ни решила модель. Подмена инструкций (injection) — приём,
# а не просьба: в обычном вопросе он встречается тоже («давай сыграем», «забудь правила и объясни…»).
FORCED_KINDS = {"dose", "treatment", "diagnosis"}


def forces_attack(kind: str | None) -> bool:
    return kind in FORCED_KINDS


def output_violation(text: str) -> bool:
    return any(rx.search(text) for rx in OUTPUT_BLOCK)


def looks_like_refusal(text: str) -> bool:
    return bool(REFUSAL_MARKERS.search(text))
